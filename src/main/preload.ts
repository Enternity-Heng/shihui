import { contextBridge, ipcRenderer } from 'electron';
import type { MathBridge } from '../shared/types';
const bridge: MathBridge = {
  state:() => ipcRenderer.invoke('math:state'),
  render:source => ipcRenderer.invoke('math:render',source),
  preview:source=>ipcRenderer.invoke('math:preview',source),
  previewPseudocode:(source,lineNumbers)=>ipcRenderer.invoke('math:pseudocode-preview',source,lineNumbers),
  previewFlowchart:value=>ipcRenderer.invoke('math:flowchart-preview',value),
  previewDiagram:value=>ipcRenderer.invoke('math:diagram-preview',value),
  outputDiagram:(value,action)=>ipcRenderer.invoke('math:diagram-output',value,action),
  copyCase:id=>ipcRenderer.invoke('math:case-copy',id),
  outputFlowchart:(value,action)=>ipcRenderer.invoke('math:flowchart-output',value,action),
  outputPseudocode:(source,lineNumbers,action)=>ipcRenderer.invoke('math:pseudocode-output',source,lineNumbers,action),
  editorVersion:version=>ipcRenderer.invoke('math:editor-version',version),
  insert:id => ipcRenderer.invoke('math:insert',id),
  insertImage:id => ipcRenderer.invoke('math:insert-image',id),
  copy:(id,type) => ipcRenderer.invoke('math:copy',id,type),
  save:id => ipcRenderer.invoke('math:save',id),
  shortcut:value => ipcRenderer.invoke('math:shortcut',value),
  recognizeImage:source=>ipcRenderer.invoke('math:recognize-image',source),
  preferences:value=>ipcRenderer.invoke('math:preferences',value),
  commands:()=>ipcRenderer.invoke('math:commands'),
  saveCommand:value=>ipcRenderer.invoke('math:save-command',value),
  deleteCommand:id=>ipcRenderer.invoke('math:delete-command',id),
  history:(query,page)=>ipcRenderer.invoke('math:history',query,page),
  historyDetail:id=>ipcRenderer.invoke('math:history-detail',id),
  historyPreview:id=>ipcRenderer.invoke('math:history-preview',id),
  deleteHistory:id=>ipcRenderer.invoke('math:delete-history',id),
  clearHistory:()=>ipcRenderer.invoke('math:clear-history'),
  favorites:()=>ipcRenderer.invoke('math:favorites'),
  saveFavorite:value=>ipcRenderer.invoke('math:save-favorite',value),
  deleteFavorite:id=>ipcRenderer.invoke('math:delete-favorite',id),
  saveCategory:value=>ipcRenderer.invoke('math:save-category',value),
  deleteCategory:id=>ipcRenderer.invoke('math:delete-category',id),
  exportFavorites:()=>ipcRenderer.invoke('math:export-favorites'),
  importFavorites:()=>ipcRenderer.invoke('math:import-favorites'),
  commitFavoritesImport:id=>ipcRenderer.invoke('math:commit-favorites-import',id),
  reviewImage:id=>ipcRenderer.invoke('math:review-image',id),
  confirmReview:(id,source)=>ipcRenderer.invoke('math:confirm-review',id,source),
  discardReview:id=>ipcRenderer.invoke('math:discard-review',id),
  restoreReview:value=>ipcRenderer.invoke('math:restore-review',value),
  draft:()=>ipcRenderer.invoke('math:draft'),
  saveDraft:(value,epoch)=>ipcRenderer.invoke('math:save-draft',value,epoch),
  flushDraft:()=>ipcRenderer.invoke('math:flush-draft'),
  clearDraft:()=>ipcRenderer.invoke('math:clear-draft'),
  onDraftStatus:callback=>{const fn=(_event:unknown,value:Parameters<typeof callback>[0])=>callback(value);ipcRenderer.on('math:draft-status',fn);return ()=>ipcRenderer.removeListener('math:draft-status',fn);},
  onCaptureRequested:callback=>{const listener=()=>callback();ipcRenderer.on('math:capture-requested',listener);return ()=>ipcRenderer.removeListener('math:capture-requested',listener);},
  cancelRecognition:()=>ipcRenderer.invoke('math:cancel-recognition'),
  onRecognitionProgress:callback=>{const listener=(_event:unknown,message:string)=>callback(message);ipcRenderer.on('math:recognition-progress',listener);return ()=>ipcRenderer.removeListener('math:recognition-progress',listener);},
  hide:() => ipcRenderer.send('math:hide'),
  onOpen:callback => { const listener = (_event:unknown, settings:boolean) => callback(settings); ipcRenderer.on('math:open',listener); return () => ipcRenderer.removeListener('math:open',listener); },
  onState:callback => { const listener = (_event:unknown, state:Parameters<typeof callback>[0]) => callback(state); ipcRenderer.on('math:state-changed',listener); return () => ipcRenderer.removeListener('math:state-changed',listener); }
};
contextBridge.exposeInMainWorld('math',bridge);
