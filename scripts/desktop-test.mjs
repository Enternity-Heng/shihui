import {_electron,expect} from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const executablePath=require('electron');
const env={...process.env,MATH_INPUT_TEST:'1',MATH_INPUT_PROFILE:path.resolve('.test-profile',`desktop-${Date.now()}`)};
delete env.ELECTRON_RUN_AS_NODE;
await fs.mkdir('test-results',{recursive:true});
const report=[];
const application=await _electron.launch({executablePath,args:['.'],env,timeout:30000});
let editorApp;
const errors=[];
application.process().stderr.on('data',chunk=>errors.push(chunk.toString()));
const record=(name)=>{report.push(name);console.log('PASS '+name);};
try{
  const page=await application.firstWindow();
  page.setDefaultTimeout(15000);
  await expect(page.locator('#source')).toBeVisible();
  await expect(page.locator('#primary')).toBeDisabled();
  expect(await application.evaluate(()=>global.__mathTest.nativeDiagnostics())).toEqual({inputSize:40,guiSize:72});
  record('启动、沙箱预加载和 Win64 原生结构布局');
  await page.locator('#source').fill('\\alpha+\\beta');
  await expect(page.locator('#plain-value')).toHaveText('α+β');
  await page.locator('#primary').click();
  await expect(page.locator('#message')).toContainText('已复制数学符号');
  expect(await application.evaluate(async({clipboard})=>await clipboard.readText())).toBe('α+β');
  record('文字符号转换与系统剪贴板');
  await page.locator('#source').fill('\\gamma');
  await page.locator('#source').press('Enter');
  await expect.poll(async()=>await application.evaluate(async({clipboard})=>await clipboard.readText())).toBe('γ');
  record('快速输入后立即回车等待最新转换');
  await page.locator('#source').fill('\\frac{-b\\pm\\sqrt{b^2-4ac}}{2a}');
  await expect(page.locator('#kind')).toHaveText('排版公式');
  await page.screenshot({path:'test-results/application.png'});
  await page.locator('#copy-image').click();
  await expect(page.locator('#message')).toContainText('已复制公式图片');
  const png=await application.evaluate(async({clipboard})=>{
    const items=await clipboard.read();
    const item=items.find(item=>item.types.includes('image/png'));
    if(!item)return null;
    const blob=await item.getType('image/png');
    return Array.from(new Uint8Array(await blob.arrayBuffer()));
  });
  expect(png).not.toBeNull();
  const pngBuffer=Buffer.from(png);
  await fs.writeFile('test-results/formula.png',pngBuffer);
  expect(pngBuffer.readUInt32BE(16)).toBeGreaterThan(100);
  expect(pngBuffer.readUInt32BE(20)).toBeGreaterThan(80);
  record('独立画布渲染与 PNG 系统剪贴板');
  const savePath=path.resolve('test-results/saved-formula.png');
  await application.evaluate(({dialog},filePath)=>{
    global.__originalSaveDialog=dialog.showSaveDialog;
    dialog.showSaveDialog=async()=>({canceled:false,filePath});
  },savePath);
  try{
    await page.locator('#save-image').click();
    await expect(page.locator('#message')).toContainText('公式图片已保存');
    expect((await fs.readFile(savePath)).subarray(0,8)).toEqual(Buffer.from([137,80,78,71,13,10,26,10]));
  }finally{await application.evaluate(({dialog})=>{dialog.showSaveDialog=global.__originalSaveDialog;});}
  record('保存 PNG 写入有效图片（测试替代路径对话框）');
  await page.locator('#source').fill('a'.repeat(500));
  await expect(page.locator('#copy-image')).toBeEnabled();
  await application.evaluate(async({clipboard})=>await clipboard.writeText('oversize-sentinel'));
  await page.locator('#copy-image').click();
  await expect(page.locator('#message')).toContainText('超过尺寸限制');
  expect(await application.evaluate(async({clipboard})=>await clipboard.readText())).toBe('oversize-sentinel');
  record('超大 PNG 拒绝导出且保留剪贴板');
  await page.locator('#source').fill('\\alpha');
  await page.locator('#source').fill('\\beta');
  await expect(page.locator('#plain-value')).toHaveText('β');
  await page.locator('#primary').click();
  await expect(page.locator('#message')).toContainText('已复制数学符号');
  expect(await application.evaluate(async({clipboard})=>await clipboard.readText())).toBe('β');
  record('快速编辑不会操作旧结果');
  const bad=await page.evaluate(()=>window.math.insert(-1));
  expect(bad.ok).toBe(false);
  await page.locator('#source').fill('\\def\\a{\\a}\\a');
  await expect(page.locator('#kind')).toHaveText('检查源码');
  await expect(page.locator('#copy-image')).toBeDisabled();
  await page.locator('#source').fill('\\href{https://example.com}{x}');
  await expect(page.locator('#kind')).toHaveText('检查源码');
  await expect(page.locator('#preview')).toContainText('不支持外部');
  record('过期操作拒绝、宏循环及外部资源阻止');
  // Composition Enter must not copy or insert the previous valid conversion.
  await page.locator('#source').fill('\\alpha');
  await expect(page.locator('#plain-value')).toHaveText('α');
  await application.evaluate(async({clipboard})=>await clipboard.writeText('composition-sentinel'));
  await page.locator('#source').evaluate(element=>{
    element.dispatchEvent(new CompositionEvent('compositionstart',{bubbles:true}));
    element.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',isComposing:true,bubbles:true,cancelable:true}));
    element.dispatchEvent(new CompositionEvent('compositionend',{bubbles:true}));
  });
  expect(await application.evaluate(async({clipboard})=>await clipboard.readText())).toBe('composition-sentinel');
  record('中文组字回车不提交');
  const settings=await page.evaluate(()=>window.math.shortcut('M'));
  expect(settings.ok).toBe(false);
  await application.evaluate(({globalShortcut})=>globalShortcut.register('Control+Alt+F9',()=>{}));
  const conflict=await page.evaluate(()=>window.math.shortcut('Control+Alt+F9'));
  expect(conflict.ok).toBe(false);
  const changed=await page.evaluate(()=>window.math.shortcut('Control+Shift+K'));
  expect(changed.ok).toBe(true);
  expect((await page.evaluate(()=>window.math.state())).shortcut).toBe('Control+Shift+K');
  expect((await page.evaluate(()=>window.math.shortcut('Control+Alt+M'))).ok).toBe(true);
  record('快捷键冲突、校验、持久化与恢复');
  // A separate Electron process acts as a real external Chromium text control.
  editorApp=await _electron.launch({executablePath,args:['tests/fixtures/editor.cjs'],env,timeout:30000});
  const editor=await editorApp.firstWindow();
  await expect(editor.locator('#editor')).toBeVisible();
  await expect.poll(async()=>await editorApp.evaluate(()=>!!global.pressHotkey)).toBe(true);
  await application.evaluate(()=>global.__mathTest.hide());
  await editorApp.evaluate(()=>global.focusEditor());
  await expect.poll(async()=>await application.evaluate(()=>global.__mathTest.captureTarget()?.title)).toBe('Math input integration editor');
  await editor.locator('#editor').click();
  await editorApp.evaluate(()=>global.pressHotkey());
  await expect(page.locator('#target')).toContainText('Math input integration editor');
  await page.locator('#source').fill('\\alpha+\\beta');
  await expect(page.locator('#plain-value')).toHaveText('α+β');
  await application.evaluate(async({clipboard})=>await clipboard.writeText('keep-clipboard'));
  await page.locator('#source').press('Enter');
  await expect(editor.locator('#editor')).toHaveValue('α+β');
  expect(await application.evaluate(async({clipboard})=>await clipboard.readText())).toBe('keep-clipboard');
  record('真实全局快捷键、跨进程焦点恢复与 Unicode 插入，保留剪贴板');
  await editorApp.evaluate(()=>global.pressHotkey());
  await expect(page.locator('#target')).toContainText('Math input integration editor');
  await editorApp.evaluate(()=>global.focusEditor());
  await expect.poll(async()=>await application.evaluate(()=>global.__mathTest.state().target)).toBeNull();
  record('切换至外部窗口取消原目标');
  await editorApp.evaluate(()=>global.pressHotkey());
  await expect(page.locator('#target')).toContainText('Math input integration editor');
  record('窗口仍可见时重新按热键可绑定新的目标');
  console.log(`Desktop tests passed: ${report.length}`);
}finally{
  if(editorApp)await editorApp.close();
  await application.close();
  await fs.writeFile('test-results/desktop-report.json',JSON.stringify({checks:report,errors},null,2));
}
